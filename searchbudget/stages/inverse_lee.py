import math

import matplotlib
import numpy as np
from scipy.optimize import brentq
from scipy.stats import norm

from .. import io, paths
from ..registry import stage
from ..viz.style import C_ALT, C_ARG, C_BKG, INK, labels, size, style

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

PLOTS = f"{paths.PLOTS}/inverse_lee"

# (label, N, pseudo-experiments): N the trials numbers of Table 1, enough toys for a few-percent p_global
BASES = [("model space, inclusive", 4319, 1_000_000),
         ("published ATLAS program", 7875, 500_000),
         ("combinatorial scan", 201_000, 20_000),
         ("combinatorial scan, lensed", 363_000, 10_000)]
Z_LOCAL = 5.0
CHUNK_LOOKS = 50_000_000


def z_closed(n):
    """Eq. (1) inverted: Z_glob^2 = Z_loc^2 - 2 ln N, zero once the right-hand side goes negative."""
    return math.sqrt(max(Z_LOCAL ** 2 - 2 * math.log(n), 0.0))


def z_with_log_term(n):
    """The same steps with 2 ln(Z_glob/Z_loc) kept: Z_glob^2 = Z_loc^2 - 2 ln N - 2 ln(Z_glob/Z_loc)."""
    f = lambda z: z * z - Z_LOCAL ** 2 + 2 * math.log(n) + 2 * math.log(z / Z_LOCAL)
    return brentq(f, 1e-6, Z_LOCAL)


def z_exact(n):
    p = -math.expm1(n * math.log1p(-norm.sf(Z_LOCAL)))
    return norm.isf(p), p


def toys(n, npe, rng):
    """Brute force: npe pseudo-experiments of n independent unit Gaussians, fraction whose maximum >= Z_LOCAL."""
    rows = max(1, CHUNK_LOOKS // n)
    hits = 0
    for i in range(0, npe, rows):
        k = min(rows, npe - i)
        hits += int((rng.standard_normal((k, n), dtype=np.float32).max(axis=1) >= Z_LOCAL).sum())
    p = hits / npe
    dp = math.sqrt(p * (1 - p) / npe)
    z = norm.isf(p)
    dz = dp / norm.pdf(z)
    return z, dz, p, hits


@stage(
    name="inverse-lee",
    group="stats",
    summary="what a local 5 sigma is worth globally: Eq. (1) inverted against the exact tail and brute-force toys",
    outputs=["tables/inverse_lee.csv", "tex/inverse_lee_table.tex", "plots/inverse_lee/inverse_lee.png"],
)
def main(options=None):
    rng = np.random.default_rng(20261001)
    out = []
    print(f"Z_glob of a local {Z_LOCAL:.0f} sigma\n")
    print(f"{'basis':<30}{'N':>9}{'Eq.(1)':>8}{'+log':>8}{'exact':>8}{'toys':>15}{'p exact':>10}{'p toys':>10}")
    for label, n, npe in BASES:
        zc, zl = z_closed(n), z_with_log_term(n)
        ze, pe = z_exact(n)
        zt, dzt, pt, hits = toys(n, npe, rng)
        out.append([label, n, npe, f"{zc:.3f}", f"{zl:.3f}", f"{ze:.3f}", f"{pe:.4g}",
                    f"{zt:.3f}", f"{dzt:.3f}", f"{pt:.4g}", hits])
        print(f"{label:<30}{n:>9}{zc:>8.2f}{zl:>8.2f}{ze:>8.2f}{zt:>9.2f}+-{dzt:.2f}{pe:>10.3g}{pt:>10.3g}")
    n_half = math.log(2) / norm.sf(Z_LOCAL)
    print(f"\nEq. (1) inverted reaches zero at N = e^12.5 = {math.exp(12.5):.3g}; "
          f"the exact Z_glob reaches zero (p_global = 0.5) at N = {n_half:.3g}")

    io.write_rows(f"{paths.TABLES}/inverse_lee.csv",
                  ["basis", "N", "toys", "z_closed_form", "z_log_term_kept", "z_exact", "p_exact",
                   "z_toys", "z_toys_err", "p_toys", "toys_above"], out)

    fmt_n = lambda n: f"${n / 10 ** int(math.log10(n)):.1f}\\times10^{{{int(math.log10(n))}}}$" \
        if n >= 10 ** 5 else f"${n:,}$".replace(",", "\\,")
    body = "\n".join(
        f"{r[0]} & {fmt_n(r[1])} & {f'{float(r[3]):.2f}' if float(r[3]) > 0 else 'none'} &{float(r[4]):.2f} & {float(r[5]):.2f} & "
        f"${float(r[7]):.2f}\\pm{float(r[8]):.2f}$ & {float(r[6]):.2g} \\\\" for r in out)
    io.write_text(f"{paths.TEX}/inverse_lee_table.tex",
                  "% Generated by searchbudget/stages/inverse_lee.py. Do not edit: regenerate instead.\n"
                  "\\begin{tabular}{lrrrrrr}\n\\toprule\n"
                  "basis & $N$ & Eq.~\\eqref{eq:lee} & log term kept & exact & toys & $p_{\\mathrm{global}}$ \\\\\n"
                  "\\midrule\n" + body + "\n\\bottomrule\n\\end{tabular}\n")

    ns = np.logspace(1, 7, 400)
    fig, ax = plt.subplots(figsize=size(0.62, 0.68))
    ax.plot(ns, [z_exact(n)[0] for n in ns], color=C_BKG, lw=1.4, label="exact, $1-(1-p)^N$")
    ax.plot(ns, [z_closed(n) for n in ns], color=C_ARG, lw=1.2, ls="--", label="Eq. (1) inverted")
    ax.plot(ns, [z_with_log_term(n) for n in ns], color=C_ALT, lw=1.0, ls=":", label=r"with $2\ln(Z_{\rm glob}/Z_{\rm loc})$ kept")
    ax.errorbar([r[1] for r in out], [float(r[7]) for r in out], yerr=[float(r[8]) for r in out],
                fmt="o", ms=3.5, color=INK, label="toys", zorder=5)
    ax.axhline(0, color=INK, lw=0.5)
    ax.set_xscale("log")
    ax.set_ylim(-0.1, 4.3)
    labels(ax, x=r"independent looks $N$", y=r"$Z_{\rm glob}$ of a local $5\sigma$")
    style(ax, minor="y")
    ax.legend(loc="lower left", frameon=False)
    io.save(fig, f"{PLOTS}/inverse_lee.png")
    plt.close(fig)
